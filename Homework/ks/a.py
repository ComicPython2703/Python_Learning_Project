# coding=utf-8
key = input("输入一个1到7的数字: ")
if key == "1":
    print("Monday")
elif key == "2":
    print("Tuesday")
elif key == "3":
    print("Wednesday")
elif key == "4":
    print("Thursday")
elif key == "5":
    print("Friday")
elif key == "6":
    print("Saturday")
elif key == "7":
    print("Sunday")
else:
    print("没有这个天!!!")